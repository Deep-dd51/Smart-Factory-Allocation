# 7. ESTIMATED DAYS SAVED
# ============================================================

def plot_days_saved(df):

    print_section(
        "7. ESTIMATED DAYS SAVED"
    )

    if (
        "estimated_days_saved"
        in df.columns
    ):

        column = "estimated_days_saved"

    elif (
        "estimated_lead_time_days_saved"
        in df.columns
    ):

        column = (
            "estimated_lead_time_days_saved"
        )

    else:

        df["estimated_days_saved"] = (
            df["lead_time_improvement_days"]
            * df["candidate_records"]
        )

        column = "estimated_days_saved"

    data = df.sort_values(
        column,
        ascending=True
    )

    labels = (
        data["product_id"]
        + "\n"
        + data["candidate_location"]
    )

    plt.figure(
        figsize=(12, 7)
    )

    plt.barh(
        labels,
        data[column]
    )

    plt.xlabel(
        "Estimated Historical Days Saved"
    )

    plt.ylabel(
        "Allocation"
    )

    plt.title(
        "Estimated Shipping Days Saved"
    )

    save_plot(
        "07_days_saved.png"
    )


