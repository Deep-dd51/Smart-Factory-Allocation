# 8. EXECUTIVE DASHBOARD
# ============================================================

def create_executive_dashboard(df):

    print_section(
        "8. EXECUTIVE SUMMARY"
    )

    total_recommendations = len(df)

    products = (
        df["product_id"]
        .nunique()
    )

    locations = (
        df["candidate_location"]
        .nunique()
    )

    avg_improvement_pct = (
        df["lead_time_improvement_pct"]
        .mean()
    )

    avg_improvement_days = (
        df["lead_time_improvement_days"]
        .mean()
    )

    max_improvement_pct = (
        df["lead_time_improvement_pct"]
        .max()
    )

    max_improvement_days = (
        df["lead_time_improvement_days"]
        .max()
    )

    if "estimated_days_saved" in df.columns:

        total_days_saved = (
            df["estimated_days_saved"]
            .sum()
        )

    elif (
        "estimated_lead_time_days_saved"
        in df.columns
    ):

        total_days_saved = (
            df[
                "estimated_lead_time_days_saved"
            ].sum()
        )

    else:

        total_days_saved = (
            df[
                "lead_time_improvement_days"
            ]
            * df["candidate_records"]
        ).sum()

    best = df.loc[
        df[
            "lead_time_improvement_pct"
        ].idxmax()
    ]

    print(
        f"""
Recommendations          : {total_recommendations}
Products involved        : {products}
Locations involved       : {locations}

Average improvement      : {avg_improvement_pct:.2f}%
Average reduction        : {avg_improvement_days:.2f} days

Maximum improvement      : {max_improvement_pct:.2f}%
Maximum reduction        : {max_improvement_days:.2f} days

Estimated total days saved: {total_days_saved:.2f}

BEST RECOMMENDATION

Product                  : {best["product_id"]}
Recommended location     : {best["candidate_location"]}
Current lead time        : {best["current_avg_lead_time"]:.2f} days
Recommended lead time    : {best["candidate_avg_lead_time"]:.2f} days
Improvement              : {best["lead_time_improvement_days"]:.2f} days
Improvement              : {best["lead_time_improvement_pct"]:.2f}%
Historical records       : {int(best["candidate_records"])}
Priority                 : {best["priority"]}
Confidence               : {best["confidence"]}
Action                   : {best["recommended_action"]}
"""
    )

    # --------------------------------------------------------
    # Dashboard figure
    # --------------------------------------------------------

    fig = plt.figure(
        figsize=(14, 9)
    )

    ax = fig.add_subplot(111)

    ax.axis("off")

    dashboard_text = f"""
FACTORY ALLOCATION OPTIMIZATION
EXECUTIVE DASHBOARD

Recommendations Evaluated : {total_recommendations}
Products Involved         : {products}
Locations Involved        : {locations}

Average Lead-Time Improvement
{avg_improvement_pct:.2f}%

Average Lead-Time Reduction
{avg_improvement_days:.2f} days

Maximum Improvement
{max_improvement_pct:.2f}%

Estimated Historical Days Saved
{total_days_saved:.2f}

--------------------------------------------

BEST RECOMMENDATION

Product:
{best["product_id"]}

Recommended Location:
{best["candidate_location"]}

Current Lead Time:
{best["current_avg_lead_time"]:.2f} days

Recommended Lead Time:
{best["candidate_avg_lead_time"]:.2f} days

Improvement:
{best["lead_time_improvement_days"]:.2f} days
({best["lead_time_improvement_pct"]:.2f}%)

Priority:
{best["priority"]}

Confidence:
{best["confidence"]}

Recommended Action:
{best["recommended_action"]}
"""

    ax.text(
        0.5,
        0.5,
        dashboard_text,
        ha="center",
        va="center",
        fontsize=15,
        family="monospace"
    )

    plt.title(
        "Factory Reallocation Executive Dashboard",
        fontsize=20,
        pad=20
    )

    save_plot(
        "08_executive_dashboard.png"
    )


