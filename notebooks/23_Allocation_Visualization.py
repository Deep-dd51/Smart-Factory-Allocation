# 1. LEAD TIME COMPARISON
# ============================================================

def plot_lead_time_comparison(df):

    print_section(
        "1. LEAD TIME COMPARISON"
    )

    data = df.sort_values(
        "lead_time_improvement_days",
        ascending=False
    )

    labels = (
        data["product_id"]
        + "\n"
        + data["candidate_location"]
    )

    x = np.arange(len(data))

    width = 0.35

    plt.figure(
        figsize=(14, 7)
    )

    plt.bar(
        x - width / 2,
        data["current_avg_lead_time"],
        width,
        label="Current Lead Time"
    )

    plt.bar(
        x + width / 2,
        data["candidate_avg_lead_time"],
        width,
        label="Recommended Lead Time"
    )

    plt.xticks(
        x,
        labels,
        rotation=45,
        ha="right"
    )

    plt.ylabel(
        "Lead Time (Days)"
    )

    plt.xlabel(
        "Product / Recommended Location"
    )

    plt.title(
        "Current vs Recommended Lead Time"
    )

    plt.legend()

    save_plot(
        "01_lead_time_comparison.png"
    )


