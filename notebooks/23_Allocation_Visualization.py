# ============================================================

def load_data():

    print_section("LOADING STEP 22 RECOMMENDATION DATA")

    if not RECOMMENDATION_PATH.exists():

        raise FileNotFoundError(
            f"""
Final recommendation dataset not found.

Expected:
{RECOMMENDATION_PATH}

Run Step 22 first:

python notebooks\\22_Recommendation_Decision_Report.py
"""
        )

    print("Final recommendations:")
    print(RECOMMENDATION_PATH)

    df = pd.read_csv(
        RECOMMENDATION_PATH
    )

    print(
        f"\nDataset shape: {df.shape}"
    )

    return df


# ============================================================
# VALIDATE DATA
# ============================================================

def validate_data(df):

    print_section("VALIDATING RECOMMENDATION DATA")

    required_columns = [
        "product_id",
        "candidate_location",
        "current_avg_lead_time",
        "candidate_avg_lead_time",
        "lead_time_improvement_days",
        "lead_time_improvement_pct",
        "candidate_records",
        "decision_score",
        "priority",
        "confidence",
        "recommended_action",
    ]

    missing = [
        col
        for col in required_columns
        if col not in df.columns
    ]

    if missing:

        print("Missing columns:")

        for col in missing:
            print(f"- {col}")

        raise ValueError(
            "\nRequired columns are missing from the "
            "Step 22 recommendation dataset."
        )

    print("Required columns: OK")

    # --------------------------------------------------------
    # Important compatibility handling
    # --------------------------------------------------------

    if (
        "recommended_avg_lead_time"
        not in df.columns
    ):

        print(
            "\nColumn compatibility:"
        )

        print(
            "recommended_avg_lead_time not found."
        )

        print(
            "Using candidate_avg_lead_time "
            "as recommended_avg_lead_time."
        )

        df[
            "recommended_avg_lead_time"
        ] = df[
            "candidate_avg_lead_time"
        ]

    print(
        f"\nValid rows: {len(df):,}"
    )

    return df


# ============================================================
# CLEAN DATA
# ============================================================

def prepare_data(df):

    print_section("PREPARING VISUALIZATION DATA")

    numeric_columns = [
        "current_avg_lead_time",
        "candidate_avg_lead_time",
        "recommended_avg_lead_time",
        "lead_time_improvement_days",
        "lead_time_improvement_pct",
        "candidate_records",
        "decision_score",
        "optimization_score",
        "estimated_days_saved",
        "estimated_lead_time_days_saved",
    ]

    for col in numeric_columns:

        if col in df.columns:

            df[col] = pd.to_numeric(
                df[col],
                errors="coerce"
            )

    df["product_id"] = (
        df["product_id"]
        .astype(str)
    )

    df["candidate_location"] = (
        df["candidate_location"]
        .astype(str)
    )

    df["priority"] = (
        df["priority"]
        .astype(str)
    )

    df["confidence"] = (
        df["confidence"]
        .astype(str)
    )

    df["recommended_action"] = (
        df["recommended_action"]
        .astype(str)
    )

    df = df.dropna(
        subset=[
            "current_avg_lead_time",
            "candidate_avg_lead_time",
            "lead_time_improvement_pct",
        ]
    )

    print(
        f"Rows available for visualization: {len(df)}"
    )

    return df


