# 5. LOCATION IMPACT
# ============================================================

def plot_location_impact(df):

    print_section(
        "5. LOCATION IMPACT"
    )

    location_summary = (
        df.groupby(
            "candidate_location"
        )
        .agg(
            products=(
                "product_id",
                "nunique"
            ),
            avg_improvement_pct=(
                "lead_time_improvement_pct",
                "mean"
            ),
            avg_improvement_days=(
                "lead_time_improvement_days",
                "mean"
            ),
            total_days_saved=(
                "estimated_days_saved",
                "sum"
            ),
        )
        .reset_index()
    )

    location_summary = (
        location_summary
        .sort_values(
            "avg_improvement_pct",
            ascending=True
        )
    )

    plt.figure(
        figsize=(12, 7)
    )

    plt.barh(
        location_summary[
            "candidate_location"
        ],
        location_summary[
            "avg_improvement_pct"
        ]
    )

    plt.xlabel(
        "Average Lead-Time Improvement (%)"
    )

    plt.ylabel(
        "Recommended Location"
    )

    plt.title(
        "Impact by Recommended Location"
    )

    save_plot(
        "05_location_impact.png"
    )

    location_summary.to_csv(
        OUTPUT_DIR
        / "location_visualization_summary.csv",
        index=False
    )


