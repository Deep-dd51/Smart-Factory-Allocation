def print_section(title):
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)


def save_plot(filename):
    output_path = OUTPUT_DIR / filename

    plt.tight_layout()
    plt.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight"
    )

    plt.close()

    print(f"Created: {output_path}")


