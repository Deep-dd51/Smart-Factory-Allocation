# ======================================================================
# MAIN
# ======================================================================

def main():

    print_header(
        "ALLOCATION OPTIMIZATION"
    )

    # --------------------------------------------------------------
    # STEP 1
    # Load Step 20 data
    # --------------------------------------------------------------

    df = load_impact_data()

    # --------------------------------------------------------------
    # STEP 2
    # Normalize column names
    # --------------------------------------------------------------

    df = normalize_columns(
        df
    )

    # --------------------------------------------------------------
    # STEP 3
    # Validate columns
    # --------------------------------------------------------------

    cols = validate_data(
        df
    )

    # --------------------------------------------------------------
    # STEP 4
    # Filter candidates
    # --------------------------------------------------------------

    qualified = filter_candidates(
        df,
        cols
    )

    # --------------------------------------------------------------
    # STEP 5
    # Calculate optimization score
    # --------------------------------------------------------------

    qualified = calculate_optimization_score(
        qualified,
        cols
    )

    # --------------------------------------------------------------
    # STEP 6
    # Select best candidate per product
    # --------------------------------------------------------------

    best = select_best_candidates(
        qualified,
        cols
    )

    # --------------------------------------------------------------
    # STEP 7
    # Build final recommendations
    # --------------------------------------------------------------

    best = build_final_recommendations(
        best,
        cols
    )

    # --------------------------------------------------------------
    # STEP 8
    # Product summary
    # --------------------------------------------------------------

    product_summary = create_product_summary(
        best,
        cols
    )

    # --------------------------------------------------------------
    # STEP 9
    # Location summary
    # --------------------------------------------------------------

    location_summary = create_location_summary(
        best,
        cols
    )

    # --------------------------------------------------------------
    # STEP 10
    # Portfolio summary
    # --------------------------------------------------------------

    portfolio = create_portfolio_summary(
        best,
        cols
    )

    # --------------------------------------------------------------
    # STEP 11
    # Save
    # --------------------------------------------------------------

    save_outputs(

        qualified,

        best,

        product_summary,

        location_summary
    )

    # --------------------------------------------------------------
    # STEP 12
    # Display results
    # --------------------------------------------------------------

    print_results(

        best,

        portfolio,

        cols
    )

    print_section(
        "ALLOCATION OPTIMIZATION COMPLETED"
    )


# ======================================================================
# ENTRY POINT
# ======================================================================

if __name__ == "__main__":

    main()