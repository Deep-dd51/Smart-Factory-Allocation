# ======================================================================
# CLEAN NUMERIC DATA
# ======================================================================

def clean_numeric_columns(
    df,
    columns
):

    df = df.copy()

    for col in columns:

        if col is None:
            continue

        df[col] = pd.to_numeric(
            df[col],
            errors="coerce"
        )

    return df


# ======================================================================
# FILTER CANDIDATES
# ======================================================================

def filter_candidates(
    df,
    cols
):

    print_section(
        "FILTERING ALLOCATION CANDIDATES"
    )

    df = df.copy()

    numeric_cols = [

        cols["current_lt"],

        cols["candidate_lt"],

        cols["improvement"],

        cols["improvement_pct"],

        cols["records"],

        cols["score"]
    ]

    df = clean_numeric_columns(
        df,
        numeric_cols
    )

    initial_count = len(df)

    # --------------------------------------------------------------
    # Valid product and location
    # --------------------------------------------------------------

    df = df[
        df[cols["product"]].notna()
        &
        df[cols["location"]].notna()
    ]

    # --------------------------------------------------------------
    # Positive improvement
    # --------------------------------------------------------------

    df = df[
        df[cols["improvement"]] > 0
    ]

    # --------------------------------------------------------------
    # Candidate must actually be faster
    # --------------------------------------------------------------

    df = df[
        df[cols["candidate_lt"]]
        <
        df[cols["current_lt"]]
    ]

    # --------------------------------------------------------------
    # Minimum historical evidence
    # --------------------------------------------------------------

    df = df[
        df[cols["records"]] >= 20
    ]

    # --------------------------------------------------------------
    # Decision score
    #
    # IMPORTANT:
    # This is the corrected expression.
    # --------------------------------------------------------------

    if cols["score"] is not None:

        df = df[
            df[cols["score"]] > 0
        ]

    df = df.reset_index(
        drop=True
    )

    print(
        f"Initial candidates : {initial_count}"
    )

    print(
        f"Qualifying         : {len(df)}"
    )

    if len(df) == 0:

        raise ValueError(
            "\nNo qualifying allocation candidates "
            "remain after filtering."
        )

    return df


# ======================================================================
# CALCULATE OPTIMIZATION SCORE
# ======================================================================

def calculate_optimization_score(
    df,
    cols
):

    print_section(
        "CALCULATING OPTIMIZATION SCORE"
    )

    df = df.copy()

    # --------------------------------------------------------------
    # Lead-time improvement score
    # Weight = 40%
    # --------------------------------------------------------------

    max_improvement = df[
        cols["improvement"]
    ].max()

    if (
        pd.notna(max_improvement)
        and max_improvement > 0
    ):

        df["lead_time_score"] = (

            df[cols["improvement"]]
            /
            max_improvement
        ) * 100

    else:

        df["lead_time_score"] = 0.0

    # --------------------------------------------------------------
    # Improvement percentage score
    # Weight = 25%
    # --------------------------------------------------------------

    max_pct = df[
        cols["improvement_pct"]
    ].max()

    if (
        pd.notna(max_pct)
        and max_pct > 0
    ):

        df["improvement_pct_score"] = (

            df[cols["improvement_pct"]]
            /
            max_pct
        ) * 100

    else:

        df["improvement_pct_score"] = 0.0

    # --------------------------------------------------------------
    # Historical reliability
    # Weight = 20%
    # --------------------------------------------------------------

    max_records = df[
        cols["records"]
    ].max()

    if (
        pd.notna(max_records)
        and max_records > 0
    ):

        df["reliability_score"] = (

            df[cols["records"]]
            /
            max_records
        ) * 100

    else:

        df["reliability_score"] = 0.0

    # --------------------------------------------------------------
    # Existing decision score
    # Weight = 15%
    # --------------------------------------------------------------

    if cols["score"] is not None:

        max_decision = df[
            cols["score"]
        ].max()

        if (
            pd.notna(max_decision)
            and max_decision > 0
        ):

            df["historical_decision_score"] = (

                df[cols["score"]]
                /
                max_decision
            ) * 100

        else:

            df["historical_decision_score"] = 0.0

    else:

        df["historical_decision_score"] = 0.0

    # --------------------------------------------------------------
    # Final optimization score
    #
    # 40% Lead-time improvement
    # 25% Improvement percentage
    # 20% Reliability
    # 15% Existing decision score
    # --------------------------------------------------------------

    df["optimization_score"] = (

        0.40
        *
        df["lead_time_score"]

        +

        0.25
        *
        df["improvement_pct_score"]

        +

        0.20
        *
        df["reliability_score"]

        +

        0.15
        *
        df["historical_decision_score"]
    )

    df["optimization_score"] = (

        df["optimization_score"]
        .clip(
            lower=0,
            upper=100
        )
        .round(3)
    )

    return df


# ======================================================================
# SELECT BEST CANDIDATE PER PRODUCT
# ======================================================================

def select_best_candidates(
    df,
    cols
):

    print_section(
        "SELECTING BEST ALLOCATION PER PRODUCT"
    )

    product_col = cols["product"]

    # --------------------------------------------------------------
    # Sort strongest candidates first
    # --------------------------------------------------------------

    df = df.sort_values(

        by=[
            product_col,

            "optimization_score",

            cols["improvement"],

            cols["records"]
        ],

        ascending=[
            True,
            False,
            False,
            False
        ]
    )

    # --------------------------------------------------------------
    # Best candidate per product
    # --------------------------------------------------------------

    best = (

        df
        .groupby(
            product_col,
            as_index=False
        )
        .first()
    )

    best = best.reset_index(
        drop=True
    )

    # --------------------------------------------------------------
    # Global rank
    # --------------------------------------------------------------

    best = best.sort_values(
        "optimization_score",
        ascending=False
    )

    best["optimization_rank"] = range(
        1,
        len(best) + 1
    )

    print(
        f"\nProducts with optimized allocation: "
        f"{len(best)}"
    )

    return best


# ======================================================================
# RECOMMENDATION TYPE
# ======================================================================

def assign_recommendation_type(
    row,
    cols
):

    improvement_pct = row[
        cols["improvement_pct"]
    ]

    improvement_days = row[
        cols["improvement"]
    ]

    records = row[
        cols["records"]
    ]

    score = row[
        "optimization_score"
    ]

    # --------------------------------------------------------------
    # Strong
    # --------------------------------------------------------------

    if (

        improvement_pct >= 15

        and

        improvement_days >= 0.75

        and

        records >= 20

        and

        score >= 60

    ):

        return "Strong Reallocation"

    # --------------------------------------------------------------
    # High
    # --------------------------------------------------------------

    elif (

        improvement_pct >= 8

        and

        improvement_days >= 0.40

        and

        records >= 20

        and

        score >= 35

    ):

        return "High Potential"

    # --------------------------------------------------------------
    # Moderate
    # --------------------------------------------------------------

    elif (

        improvement_pct >= 4

        and

        improvement_days >= 0.15

        and

        records >= 20

        and

        score >= 20

    ):

        return "Moderate Potential"

    # --------------------------------------------------------------
    # Low
    # --------------------------------------------------------------

    else:

        return "Low Priority"


# ======================================================================
# BUILD FINAL RECOMMENDATIONS
# ======================================================================

def build_final_recommendations(
    best,
    cols
):

    best = best.copy()

    # --------------------------------------------------------------
    # Recommendation type
    # --------------------------------------------------------------

    best["recommendation_type"] = best.apply(

        lambda row:

        assign_recommendation_type(
            row,
            cols
        ),

        axis=1
    )

    # --------------------------------------------------------------
    # Estimated days saved
    #
    # Historical candidate records are used as the scale factor.
    # --------------------------------------------------------------

    best[
        "estimated_lead_time_days_saved"
    ] = (

        best[cols["improvement"]]

        *

        best[cols["records"]]
    )

    best[
        "estimated_lead_time_days_saved"
    ] = (

        best[
            "estimated_lead_time_days_saved"
        ]
        .round(3)
    )

    # --------------------------------------------------------------
    # Sort final recommendations
    # --------------------------------------------------------------

    best = best.sort_values(

        by=[
            "optimization_score",
            cols["improvement"],
            cols["records"]
        ],

        ascending=[
            False,
            False,
            False
        ]
    )

    # --------------------------------------------------------------
    # Final rank
    # --------------------------------------------------------------

    best["final_rank"] = range(
        1,
        len(best) + 1
    )

    return best


# ======================================================================
# PRODUCT SUMMARY
# ======================================================================

def create_product_summary(
    best,
    cols
):

    summary = best[
        [
            cols["product"],

            cols["location"],

            cols["current_lt"],

            cols["candidate_lt"],

            cols["improvement"],

            cols["improvement_pct"],

            cols["records"],

            "optimization_score",

            "recommendation_type"
        ]
    ].copy()

    summary.columns = [

        "Product ID",

        "Recommended Location",

        "Current Avg Lead Time",

        "Optimized Avg Lead Time",

        "Improvement Days",

        "Improvement Percent",

        "Historical Records",

        "Optimization Score",

        "Recommendation"
    ]

    return summary


# ======================================================================
# LOCATION SUMMARY
# ======================================================================

def create_location_summary(
    best,
    cols
):

    location_col = cols["location"]

    summary = (

        best

        .groupby(
            location_col
        )

        .agg(

            products_recommended=(
                cols["product"],
                "count"
            ),

            avg_improvement_days=(
                cols["improvement"],
                "mean"
            ),

            avg_improvement_pct=(
                cols["improvement_pct"],
                "mean"
            ),

            max_improvement_pct=(
                cols["improvement_pct"],
                "max"
            ),

            total_historical_records=(
                cols["records"],
                "sum"
            ),

            avg_optimization_score=(
                "optimization_score",
                "mean"
            )
        )

        .reset_index()
    )

    summary = summary.sort_values(

        "avg_optimization_score",

        ascending=False
    )

    return summary


# ======================================================================
# PORTFOLIO SUMMARY
# ======================================================================

def create_portfolio_summary(
    best,
    cols
):

    total_products = best[
        cols["product"]
    ].nunique()

    total_locations = best[
        cols["location"]
    ].nunique()

    avg_improvement_pct = best[
        cols["improvement_pct"]
    ].mean()

    avg_improvement_days = best[
        cols["improvement"]
    ].mean()

    total_days_saved = best[
        "estimated_lead_time_days_saved"
    ].sum()

    max_improvement_pct = best[
        cols["improvement_pct"]
    ].max()

    max_improvement_days = best[
        cols["improvement"]
    ].max()

    return {

        "products_optimized":
            total_products,

        "locations_involved":
            total_locations,

        "average_improvement_pct":
            avg_improvement_pct,

        "average_improvement_days":
            avg_improvement_days,

        "maximum_improvement_pct":
            max_improvement_pct,

        "maximum_improvement_days":
            max_improvement_days,

        "estimated_total_days_saved":
            total_days_saved
    }


