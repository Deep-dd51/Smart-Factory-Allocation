# ======================================================================
# NORMALIZE COLUMN NAMES
# ======================================================================

def normalize_columns(df):

    df = df.copy()

    df.columns = (
        df.columns
        .astype(str)
        .str.strip()
        .str.lower()
        .str.replace(
            " ",
            "_",
            regex=False
        )
        .str.replace(
            "-",
            "_",
            regex=False
        )
    )

    return df


# ======================================================================
# FIND COLUMN
# ======================================================================

def find_column(
    df,
    possible_names,
    required=True
):

    for name in possible_names:

        name = name.lower()

        if name in df.columns:

            return name

    if required:

        raise KeyError(
            "\nRequired column not found.\n"
            f"Expected one of: {possible_names}\n\n"
            f"Available columns:\n{list(df.columns)}"
        )

    return None


