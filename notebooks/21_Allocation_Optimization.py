# ======================================================================
# FILE DISCOVERY
# ======================================================================

def find_file(filename):
    """
    Recursively search data/processed for a required file.

    This prevents problems caused by slightly different folder
    structures between previous pipeline steps.
    """

    matches = list(
        PROCESSED_DIR.rglob(filename)
    )

    if not matches:
        return None

    # Prefer files inside factory allocation folders
    preferred = [
        path
        for path in matches
        if "factory_allocation" in str(path).lower()
    ]

    if preferred:
        return preferred[0]

    return matches[0]


